let current = 'zh';

export function setUiLang(code) {
  if (DICT[code]) current = code;
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  }
  return current;
}

export function getUiLang() {
  return current;
}

export function t(key, vars) {
  const table = DICT[current] || DICT.zh;
  let text = table[key];
  if (text === undefined) text = DICT.zh[key];
  if (text === undefined) return key;
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
  }
  return text;
}

/** 应用 data-i18n / data-i18n-title / data-i18n-placeholder 到 DOM */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}
